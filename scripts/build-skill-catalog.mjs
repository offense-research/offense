import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { TOOL_CATALOG } from '../shared/tool-catalog.js';

export function renderSkillCatalog(tools = TOOL_CATALOG) {
  const sections = tools.map(tool => {
    const lines = [
      `## \`${tool.id}\` — ${tool.name}`,
      '',
      `Input family: \`${tool.inputType}\`.`,
    ];
    if (tool.requiredInput?.length) lines.push(`Required fields: ${tool.requiredInput.map(field => `\`${field}\``).join(', ')}.`);
    if (tool.kubernetesVersions?.length) lines.push(`Supported Kubernetes versions: ${tool.kubernetesVersions.map(version => `\`${version}\``).join(', ')}.`);
    lines.push('', tool.coverage);
    return lines.join('\n');
  });
  const introduction = [
    '# Tool capability catalog',
    '',
    '<!-- Generated by scripts/build-skill-catalog.mjs from shared/tool-catalog.js; do not edit. -->',
    '',
    'This is static capability information, not a promise that a tool is enabled or free. Runtime discovery through `offense.security_tools` or the CLI is authoritative for availability, current input contracts and pricing. Obtain a current quote before paid execution.',
    '',
    'Required fields below are those explicitly declared in the static catalog; their absence is not an empty input contract. Inspect runtime tool details and the [tool operations guide](tools.md) before execution. Choose checks using [check selection](check-selection.md), preserving the requested scope and existing authorization.',
  ].join('\n');
  return [introduction, ...sections].join('\n\n') + '\n';
}

export async function buildSkillCatalog(target = new URL('../public/skills/offense/references/catalog.md', import.meta.url)) {
  await writeFile(target, renderSkillCatalog());
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await buildSkillCatalog();
